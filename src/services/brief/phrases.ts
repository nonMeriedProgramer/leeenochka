async function pick(kind: 'greeting' | 'quote', pool: string[], cooldownDays: number): Promise<string> {
  const rows = await db.query<{ text: string }>(
    `SELECT text FROM brief_phrases WHERE kind = $1 AND used_at > now() - ($2 || ' days')::interval`,
    [kind, cooldownDays],
  );
  const usedRecently = new Set(rows.map((r) => r.text));
  const eligible = pool.filter((p) => !usedRecently.has(p));
  const from = eligible.length ? eligible : pool;
  const chosen = from[Math.floor(Math.random() * from.length)];
  await db.run(
    `INSERT INTO brief_phrases (kind, text, used_at) VALUES ($1, $2, now())
     ON CONFLICT (kind, text) DO UPDATE SET used_at = now()`,
    [kind, chosen],
  );
  return chosen;
}

/** Не повторюється ~місяць. */
export const pickGreeting = (): Promise<string> => pick('greeting', GREETINGS, 30);
/** Не повторюється ~три місяці. */
export const pickQuote = (): Promise<string> => pick('quote', QUOTES, 90);
